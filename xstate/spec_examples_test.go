// examplesCd1Machine mirrors the describe-level `machine` in examples/cd.test.ts:5-48.
func examplesCd1Machine() *xs.StateMachine[any] {
	return xs.CreateMachine(xs.MachineConfig[any]{
		Initial: "not_loaded",
		States: xs.States{
			{
				Key: "not_loaded",
				On: map[string]xs.Transitions{
					"INSERT_CD": {{Target: "loaded"}},
				},
			},
			{
				Key:     "loaded",
				Initial: "stopped",
				On: map[string]xs.Transitions{
					"EJECT": {{Target: "not_loaded"}},
				},
				States: xs.States{
					{
						Key: "stopped",
						On: map[string]xs.Transitions{
							"PLAY": {{Target: "playing"}},
						},
					},
					{
						Key: "playing",
						On: map[string]xs.Transitions{
							"STOP":        {{Target: "stopped"}},
							"EXPIRED_END": {{Target: "stopped"}},
							"EXPIRED_MID": {{Target: "playing"}},
							"PAUSE":       {{Target: "paused"}},
						},
					},
					{
						Key:     "paused",
						Initial: "not_blank",
						States: xs.States{
							{Key: "blank", On: map[string]xs.Transitions{"TIMER": {{Target: "not_blank"}}}},
							{Key: "not_blank", On: map[string]xs.Transitions{"TIMER": {{Target: "blank"}}}},
						},
						On: map[string]xs.Transitions{
							"PAUSE": {{Target: "playing"}},
							"PLAY":  {{Target: "playing"}},
							"STOP":  {{Target: "stopped"}},
						},
					},
				},
			},
		},
	})
}

// examplesCd1ResolveSerializedStateValue mirrors resolveSerializedStateValue in test/utils.ts:10-16.
func examplesCd1ResolveSerializedStateValue(t *testing.T, machine *xs.StateMachine[any], serialized string) *xs.MachineSnapshot[any] {
	t.Helper()
	if serialized[0] == '{' {
		var value any
		require.NoError(t, json.Unmarshal([]byte(serialized), &value))
		return machine.ResolveState(xs.ResolveStateConfig[any]{Value: value, Context: map[string]any{}})
	}
	return machine.ResolveState(xs.ResolveStateConfig[any]{Value: serialized, Context: map[string]any{}})
}

var examplesCd1EventSplit = regexp.MustCompile(`,\s?`)

// examplesCd1TestMultiTransition mirrors testMultiTransition in test/utils.ts:18-44.
func examplesCd1TestMultiTransition(t *testing.T, machine *xs.StateMachine[any], fromState, eventTypes string) *xs.MachineSnapshot[any] {
	t.Helper()
	state := examplesCd1ResolveSerializedStateValue(t, machine, fromState)
	for _, eventType := range examplesCd1EventSplit.Split(eventTypes, -1) {
		state = xs.GetNextSnapshot[*xs.MachineSnapshot[any]](machine, state, xs.Ev(eventType))
	}
	return state
}

// examplesCd1TestAllCase mirrors the body of each it() generated by testAll in
// test/utils.ts:46-72. toState == nil mirrors `undefined` (no transition).
func examplesCd1TestAllCase(t *testing.T, fromState, eventTypes string, toState xs.StateValue) {
	t.Helper()
	machine := examplesCd1Machine()
	resultState := examplesCd1TestMultiTransition(t, machine, fromState, eventTypes)

	switch ts := toState.(type) {
	case nil:
		// undefined means that the state didn't transition
		assert.Equal(t, examplesCd1ResolveSerializedStateValue(t, machine, fromState).Value, resultState.Value)
	case string:
		assert.True(t, xs.MatchesState(ts, resultState.Value))
	default:
		assert.Equal(t, toState, resultState.Value)
	}
}

