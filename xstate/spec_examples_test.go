// examples6171ResolveSerializedStateValue mirrors resolveSerializedStateValue
// from test/utils.ts: a serialized value starting with '{' is JSON-parsed,
// otherwise it is used as a string state value.
func examples6171ResolveSerializedStateValue(t *testing.T, machine *xs.StateMachine[any], serialized string) *xs.MachineSnapshot[any] {
	t.Helper()
	if serialized != "" && serialized[0] == '{' {
		var value any
		if err := json.Unmarshal([]byte(serialized), &value); err != nil {
			t.Fatalf("invalid serialized state value %q: %v", serialized, err)
		}
		return machine.ResolveState(xs.ResolveStateConfig[any]{Value: value, Context: map[string]any{}})
	}
	return machine.ResolveState(xs.ResolveStateConfig[any]{Value: serialized, Context: map[string]any{}})
}

