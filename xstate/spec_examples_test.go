// examples6161ResolveSerializedStateValue mirrors resolveSerializedStateValue
// from test/utils.ts.
func examples6161ResolveSerializedStateValue(t *testing.T, machine *xs.StateMachine[any], serialized string) *xs.MachineSnapshot[any] {
	t.Helper()
	if serialized[0] == '{' {
		var value any
		require.NoError(t, json.Unmarshal([]byte(serialized), &value))
		return machine.ResolveState(xs.ResolveStateConfig[any]{Value: value, Context: map[string]any{}})
	}
	return machine.ResolveState(xs.ResolveStateConfig[any]{Value: serialized, Context: map[string]any{}})
}

var examples6161EventSplit = regexp.MustCompile(`,\s?`)

// examples6161TestMultiTransition mirrors testMultiTransition from test/utils.ts.
func examples6161TestMultiTransition(t *testing.T, machine *xs.StateMachine[any], fromState string, eventTypes string) *xs.MachineSnapshot[any] {
	t.Helper()
	state := examples6161ResolveSerializedStateValue(t, machine, fromState)
	for _, eventType := range examples6161EventSplit.Split(eventTypes, -1) {
		state = xs.GetNextSnapshot[*xs.MachineSnapshot[any]](machine, state, xs.Ev(eventType))
	}
	return state
}

// examples6161TestAllCase mirrors the body of each it() generated by testAll
// from test/utils.ts. toState == nil mirrors `undefined` (no transition).
func examples6161TestAllCase(t *testing.T, fromState string, eventTypes string, toState xs.StateValue) {
	t.Helper()
	machine := examples6161Machine()
	resultState := examples6161TestMultiTransition(t, machine, fromState, eventTypes)

	switch ts := toState.(type) {
	case nil:
		// undefined means that the state didn't transition
		assert.Equal(t, examples6161ResolveSerializedStateValue(t, machine, fromState).Value, resultState.Value)
	case string:
		assert.True(t, xs.MatchesState(ts, resultState.Value))
	default:
		assert.Equal(t, toState, resultState.Value)
	}
}

