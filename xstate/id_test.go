// JS: State node IDs > should not treat escaped backslash as period's escape
// JS test: https://github.com/statelyai/xstate/blob/38dcaffb20ec7f3cbb10e6161d8f0ebacca33701/packages/core/test/id.test.ts#L186
func TestId_StateNodeIDs_ShouldNotTreatEscapedBackslashAsPeriodsEscape(t *testing.T) {
	machine := xs.CreateMachine(xs.MachineConfig[any]{
		Initial: "start",
		States: xs.States{
			{Key: "start", On: map[string]xs.Transitions{
				// JS source '#some\\\\.thing' is the runtime string #some\\.thing
				"EV": {{Target: `#some\\.thing`}},
			}},
			// JS source 'some\\.thing' is the runtime string some\.thing
			{Key: "foo", ID: `some\.thing`},
			{
				Key: "bar",
				// JS source 'some\\' is the runtime string some\
				ID:      `some\`,
				Initial: "baz",
				States: xs.States{
					{Key: "baz"},
					{Key: "thing"},
				},
			},
		},
	})

	initialState := xs.GetInitialSnapshot(machine)
	escapedState := xs.GetNextSnapshot(machine, initialState, xs.Ev("EV"))

	assert.Equal(t, map[string]any{"bar": "thing"}, escapedState.Value)
}
