// JS: State node IDs > should work with ID + relative path
// JS test: https://github.com/statelyai/xstate/blob/38dcaffb20ec7f3cbb10e6161d8f0ebacca33701/packages/core/test/id.test.ts#L76
func TestId_StateNodeIDs_ShouldWorkWithIDPlusRelativePath(t *testing.T) {
	machine := xs.CreateMachine(xs.MachineConfig[any]{
		Initial: "foo",
		On: map[string]xs.Transitions{
			"ACTION": {{Target: "#bar.qux.quux"}},
		},
		States: xs.States{
			{Key: "foo", ID: "foo"},
			{
				Key:     "bar",
				ID:      "bar",
				Initial: "baz",
				States: xs.States{
					{Key: "baz"},
					{
						Key:     "qux",
						Initial: "quux",
						States: xs.States{
							{Key: "quux", ID: "#bar.qux.quux"},
						},
					},
				},
			},
		},
	})

	actorRef := xs.CreateActor(machine).Start()

	actorRef.Send(xs.Ev("ACTION"))

	assert.Equal(t, map[string]any{
		"bar": map[string]any{
			"qux": "quux",
		},
	}, actorRef.GetSnapshot().Value)
}

// JS: State node IDs > should work with keys that have escaped periods
// JS test: https://github.com/statelyai/xstate/blob/38dcaffb20ec7f3cbb10e6161d8f0ebacca33701/packages/core/test/id.test.ts#L117
func TestId_StateNodeIDs_ShouldWorkWithKeysThatHaveEscapedPeriods(t *testing.T) {
	machine := xs.CreateMachine(xs.MachineConfig[any]{
		Initial: "start",
		States: xs.States{
			{Key: "start", On: map[string]xs.Transitions{
				"escaped":   {{Target: `foo\.bar`}},
				"unescaped": {{Target: "foo.bar"}},
			}},
			{Key: "foo.bar"},
			{
				Key:     "foo",
				Initial: "bar",
				States: xs.States{
					{Key: "bar"},
				},
			},
		},
	})

	initialState := xs.GetInitialSnapshot(machine)
	escapedState := xs.GetNextSnapshot(machine, initialState, xs.Ev("escaped"))

	assert.Equal(t, "foo.bar", escapedState.Value)

	unescapedState := xs.GetNextSnapshot(machine, initialState, xs.Ev("unescaped"))
	assert.Equal(t, map[string]any{"foo": "bar"}, unescapedState.Value)
}

