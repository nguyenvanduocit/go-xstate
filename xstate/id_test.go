// id1IDMachine mirrors the top-level `idMachine` of id.test.ts (lines 9-54).
func id1IDMachine() *xs.StateMachine[any] {
	return xs.CreateMachine(xs.MachineConfig[any]{
		Initial: "A",
		States: xs.States{
			{
				Key:     "A",
				ID:      "A",
				Initial: "foo",
				States: xs.States{
					{Key: "foo", ID: "A_foo", On: map[string]xs.Transitions{
						"NEXT": {{Target: "#A_bar"}},
					}},
					{Key: "bar", ID: "A_bar", On: map[string]xs.Transitions{
						"NEXT": {{Target: "#B_foo"}},
					}},
				},
				On: map[string]xs.Transitions{
					"NEXT_DOT_RESOLVE": {{Target: "#B.bar"}},
				},
			},
			{
				Key:     "B",
				ID:      "B",
				Initial: "foo",
				States: xs.States{
					{Key: "foo", ID: "B_foo", On: map[string]xs.Transitions{
						"NEXT":     {{Target: "#B_bar"}},
						"NEXT_DOT": {{Target: "#B.dot"}},
					}},
					{Key: "bar", ID: "B_bar", On: map[string]xs.Transitions{
						"NEXT": {{Target: "#A_foo"}},
					}},
					{Key: "dot"},
				},
			},
		},
	})
}

// id1ResolveSerializedStateValue mirrors resolveSerializedStateValue from
// test/utils.ts.
func id1ResolveSerializedStateValue(t *testing.T, machine *xs.StateMachine[any], serialized string) *xs.MachineSnapshot[any] {
	t.Helper()
	if serialized[0] == '{' {
		var value any
		require.NoError(t, json.Unmarshal([]byte(serialized), &value))
		return machine.ResolveState(xs.ResolveStateConfig[any]{Value: value, Context: map[string]any{}})
	}
	return machine.ResolveState(xs.ResolveStateConfig[any]{Value: serialized, Context: map[string]any{}})
}

var id1EventSplit = regexp.MustCompile(`,\s?`)

// id1TestMultiTransition mirrors testMultiTransition from test/utils.ts.
func id1TestMultiTransition(t *testing.T, machine *xs.StateMachine[any], fromState string, eventTypes string) *xs.MachineSnapshot[any] {
	t.Helper()
	state := id1ResolveSerializedStateValue(t, machine, fromState)
	for _, eventType := range id1EventSplit.Split(eventTypes, -1) {
		state = xs.GetNextSnapshot[*xs.MachineSnapshot[any]](machine, state, xs.Ev(eventType))
	}
	return state
}

// id1TestAllCase mirrors the body of each it() generated by testAll from
// test/utils.ts. toState == nil mirrors `undefined` (no transition).
func id1TestAllCase(t *testing.T, fromState string, eventTypes string, toState xs.StateValue) {
	t.Helper()
	machine := id1IDMachine()
	resultState := id1TestMultiTransition(t, machine, fromState, eventTypes)

	switch ts := toState.(type) {
	case nil:
		// undefined means that the state didn't transition
		assert.Equal(t, id1ResolveSerializedStateValue(t, machine, fromState).Value, resultState.Value)
	case string:
		assert.True(t, xs.MatchesState(ts, resultState.Value))
	default:
		assert.Equal(t, toState, resultState.Value)
	}
}

